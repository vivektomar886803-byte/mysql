SELECT CONCAT(
UPPER(SUBSTRING(FIRSTNAME, 1,3)),
LOWER(RIGHT(LASTNAME, 2))) AS NEW_NAME
FROM COURSEENROLLMENTS;

SELECT
FEE,
 ROUND(FEE, 1) AS ROUND_ONE,
 ROUND(FEE, 2) AS ROUND_TWO
FROM COURSEENROLLMENTS;

SELECT FEE,
CEIL(FEE) AS UP,
FLOOR(FEE) AS DOWN
FROM COURSEENROLLMENTS;

SELECT FEE,
MOD(FEE, 500) AS MODE_VALUE
FROM COURSEENROLLMENTS;

SELECT FEE,
ABS(FEE - 10000) AS ABS_VALUE
FROM COURSEENROLLMENTS;

SELECT FEE,
ROUND(FEE * 1.8,2) AS MULTI_VALUE
FROM COURSEENROLLMENTS;

SELECT FEE,
FORMAT(FEE, 2) AS FORMATE_FEE
FROM COURSEENROLLMENTS;

SELECT EnrollmentDate,

FROM COURSEENROLLMENTS;

SELECT ENROLLMENTDATE, DATE_ADD(
DATE_ADD(
DATE_ADD(ENROLLMENTDATE, interval 1 YEAR),
INTERVAL 2 MONTH), INTERVAL 5 DAY) AS UPDATED_DATE
FROM COURSEENROLLMENTS;

SELECT ENROLLMENTDATE,
DAYNAME(ENROLLMENTDATE) AS ENROLLMENT_DAY,
COMPLETIONDATE, DAYNAME(COMPLETIONDATE) AS COMPLETION_DAY
FROM COURSEENROLLMENTS;

SELECT ENROLLMENTDATE,
CURDATE() AS TODAY_DATE,

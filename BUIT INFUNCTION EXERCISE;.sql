SELECT FIRSTNAME,
LPAD(FIRSTNAME, 12 , 0) AS LPAD_VALUE
FROM COURSEENROLLMENTS;

SELECT  CONCAT(
RIGHT(COURSENAME, 2),'-', 
LEFT(FIRSTNAME, 2)) AS NEW_VALUE
